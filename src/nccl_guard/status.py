from enum import StrEnum


class Status(StrEnum):
    PASS = "PASS"
    FAIL = "FAIL"
    FAIL_GPU_EXECUTION = "FAIL_GPU_EXECUTION"
    INVALID_CONFIGURATION = "INVALID_CONFIGURATION"
    VALID_BUT_OOM = "VALID_BUT_OOM"
    SKIP_UNSUPPORTED = "SKIP_UNSUPPORTED"
    SKIP_NEEDS_CREDENTIALS = "SKIP_NEEDS_CREDENTIALS"
    SKIP_LICENSE_OR_TERMS = "SKIP_LICENSE_OR_TERMS"
    SKIP_VERSION_MISMATCH = "SKIP_VERSION_MISMATCH"
    SKIP_RESOURCE_BUDGET = "SKIP_RESOURCE_BUDGET"
    NOT_COMPARABLE = "NOT_COMPARABLE"

    @property
    def is_success(self) -> bool:
        return self is Status.PASS


class Verdict(StrEnum):
    BENCHMARK_QUALIFIED = "BENCHMARK_QUALIFIED"
    CONDITIONALLY_QUALIFIED = "CONDITIONALLY_QUALIFIED"
    HOLD = "HOLD"
